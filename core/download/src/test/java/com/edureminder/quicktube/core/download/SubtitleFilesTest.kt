package com.edureminder.quicktube.core.download

import com.edureminder.quicktube.core.model.SubtitleTrack
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

class SubtitleFilesTest {
    @Test
    fun manualCaptionsBecomeSrt() {
        val vtt = "WEBVTT\nKind: captions\nLanguage: en\n\n00:00:01.126 --> 00:00:03.879 align:start position:0%\n[RINGING]\n\n" +
            "01:02:03.000 --> 01:02:04.500\n<i>Hello</i> &amp; welcome\nsecond line\n"
        assertEquals(
            "1\n00:00:01,126 --> 00:00:03,879\n[RINGING]\n\n2\n01:02:03,000 --> 01:02:04,500\nHello & welcome\nsecond line\n\n",
            SubtitleFiles.vttToSrt(vtt),
        )
    }

    @Test
    fun autoCaptionsLoseTheirRepeatsAndFillers() {
        val vtt = """WEBVTT

00:00:01.000 --> 00:00:03.000 align:start position:0%
the<00:00:01.500><c> club</c>

00:00:03.000 --> 00:00:03.010 align:start position:0%
the club

00:00:03.010 --> 00:00:05.000 align:start position:0%
the club
isn't<00:00:03.500><c> the best</c>
"""
        assertEquals("1\n00:00:01,000 --> 00:00:03,000\nthe club\n\n2\n00:00:03,010 --> 00:00:05,000\nisn't the best\n\n", SubtitleFiles.vttToSrt(vtt))
    }

    @Test
    fun picksTheBestTrack() {
        fun t(lang: String, auto: Boolean = false) = SubtitleTrack(lang, lang, "u/$lang/$auto", autoGenerated = auto)
        assertEquals("bn", SubtitleFiles.pick(listOf(t("en"), t("bn"), t("bn", true)), "bn")!!.language)
        assertEquals("en-GB", SubtitleFiles.pick(listOf(t("hi"), t("en-GB")), "bn")!!.language)
        assertEquals("hi", SubtitleFiles.pick(listOf(t("hi"), t("en", true)), "bn")!!.language)
        assertEquals(true, SubtitleFiles.pick(listOf(t("en", true), t("fr", true)), "bn")!!.autoGenerated)
        assertNull(SubtitleFiles.pick(listOf(t("fr", true)), "bn"))
        assertEquals("Song(720p).en.srt", SubtitleFiles.nameFor("Song(720p).mp4", "en"))
    }
}
