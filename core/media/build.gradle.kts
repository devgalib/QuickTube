import java.security.MessageDigest
import java.util.zip.ZipFile

plugins {
    alias(libs.plugins.quicktube.android.library)
}

dependencies {
    api(projects.core.model)
    implementation(projects.core.common)
    implementation(projects.core.data)
    api(libs.androidx.media3.exoplayer)
    implementation(libs.androidx.media3.exoplayer.dash)
    implementation(libs.androidx.media3.exoplayer.hls)
    api(libs.androidx.media3.session)
    // Software audio decoders for codecs phones often lack (AC-3, E-AC-3, DTS, TrueHD, WMA); used only as a fallback.
    implementation(libs.media3.ffmpeg.decoder)
    // Software video decoders (10-bit HEVC…) for video the phone can't decode. Only its Java side ships in the APK; the
    // native libraries are downloaded on demand (see VideoDecoderPack and scripts/publish-ffmpeg-pack.sh).
    implementation(libs.nextlib.media3ext)
    implementation(libs.okhttp)
    implementation(libs.androidx.core.ktx)
}

// ---- On-demand FFmpeg video decoder pack ----
// The native libraries of nextlib-media3ext, per CPU type, published unchanged as assets of a QuickTube prerelease.
// Their names, sizes and SHA-256s are compiled into the app, which refuses any file that doesn't match.

val ffmpegPackVersion: String = libs.versions.nextlib.get()
val ffmpegPackTag = "ffmpeg-video-$ffmpegPackVersion"
val ffmpegPackAbis = listOf("arm64-v8a", "armeabi-v7a")

val ffmpegPackAar: Configuration by configurations.creating {
    isTransitive = false
    isCanBeConsumed = false
}
dependencies { ffmpegPackAar(libs.nextlib.media3ext) }

/** Copies the pack's files to build/ffmpeg-pack as `<abi>.<lib>.so`, the asset names on the release. */
val exportFfmpegPack by tasks.registering(Sync::class) {
    from(zipTree(ffmpegPackAar.elements.map { it.single().asFile })) {
        include(ffmpegPackAbis.map { "jni/$it/*.so" })
        eachFile { path = "${relativePath.segments[1]}.$name" }
    }
    includeEmptyDirs = false
    into(layout.buildDirectory.dir("ffmpeg-pack"))
}

abstract class GenerateFfmpegPackManifest : DefaultTask() {
    @get:InputFiles abstract val aar: ConfigurableFileCollection
    @get:Input abstract val tag: Property<String>
    @get:Input abstract val baseUrl: Property<String>
    @get:Input abstract val abis: ListProperty<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val entries = ZipFile(aar.singleFile).use { zip ->
            abis.get().associateWith { abi ->
                zip.entries().asSequence().filter { it.name.startsWith("jni/$abi/") && it.name.endsWith(".so") }
                    .sortedBy { it.name }
                    .map { e ->
                        val bytes = zip.getInputStream(e).readBytes()
                        val sha = MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }
                        Triple(e.name.substringAfterLast('/'), bytes.size.toLong(), sha)
                    }.toList()
            }
        }
        val body = entries.entries.joinToString(",\n") { (abi, files) ->
            "        \"$abi\" to listOf(\n" + files.joinToString(",\n") { (n, s, h) -> "            PackFile(\"$n\", $s, \"$h\")" } + ",\n        )"
        }
        val dir = outputDir.get().asFile.resolve("com/edureminder/quicktube/core/media")
        dir.mkdirs()
        dir.resolve("FfmpegPackManifest.kt").writeText(
            """
            |// Generated by :core:media:generateFfmpegPackManifest from the nextlib-media3ext AAR. Do not edit.
            |package com.edureminder.quicktube.core.media
            |
            |internal object FfmpegPackManifest {
            |    const val TAG = "${tag.get()}"
            |    const val BASE_URL = "${baseUrl.get()}"
            |    val files: Map<String, List<PackFile>> = mapOf(
            |$body,
            |    )
            |}
            |""".trimMargin(),
        )
    }
}

val generateFfmpegPackManifest by tasks.registering(GenerateFfmpegPackManifest::class) {
    aar.from(ffmpegPackAar)
    tag = ffmpegPackTag
    // Override with -PffmpegPackUrl=http://localhost:8766 to test against files served locally (adb reverse).
    baseUrl = (findProperty("ffmpegPackUrl") as String?) ?: "https://github.com/devgalib/QuickTube/releases/download"
    abis = ffmpegPackAbis
    outputDir = layout.buildDirectory.dir("generated/ffmpegPack")
}

androidComponents {
    onVariants { variant ->
        variant.sources.kotlin?.addGeneratedSourceDirectory(generateFfmpegPackManifest, GenerateFfmpegPackManifest::outputDir)
    }
}
